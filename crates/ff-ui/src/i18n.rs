fn table() -> &'static HashMap<&'static str, &'static str> {
    static T: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    T.get_or_init(|| EN.iter().copied().collect())
}

/// Traduit une chaîne (clé = texte français). Retourne la clé si aucune traduction n'existe.
pub fn tr<'a>(l: Lang, fr: &'a str) -> &'a str {
    match l {
        Lang::Fr => fr,
        Lang::En => table().get(fr).copied().unwrap_or(fr),
    }
}

/// Traduit puis remplace les marqueurs `{x}` par leurs valeurs.
pub fn trf(l: Lang, fr: &str, vars: &[(&str, String)]) -> String {
    let mut s = tr(l, fr).to_string();
    for (k, v) in vars {
        s = s.replace(k, v);
    }
    s
}

