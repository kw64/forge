    /// Toute chaîne passée littéralement à `tr(l, "…")` / `trf(l, "…"` doit avoir sa traduction.
    #[test]
    fn all_literal_calls_are_translated() {
        let mut missing = Vec::new();
        for src in [include_str!("app.rs"), include_str!("edit.rs"), include_str!("tools.rs"), include_str!("spec_ui.rs")] {
            let src = src.split("#[cfg(test)]").next().unwrap();
            for pat in ["tr(l, \"", "trf(\n                    l,\n                    \"", "trf(l, \""] {
                let mut rest = src;
                while let Some(i) = rest.find(pat) {
                    rest = &rest[i + pat.len()..];
                    let mut end = 0;
                    let b = rest.as_bytes();
                    while end < b.len() && !(b[end] == b'"' && b[end - 1] != b'\\') {
                        end += 1;
                    }
                    let key = rest[..end].replace("\\n", "\n").replace("\\\"", "\"");
                    if !table().contains_key(key.as_str()) {
                        missing.push(key);
                    }
                }
            }
        }
        missing.sort();
        missing.dedup();
        assert!(missing.is_empty(), "traductions manquantes : {missing:#?}");
    }

    #[test]
    fn builtin_labels_translated() {
        for p in ff_core::builtin_profiles() {
            assert_ne!(tr(Lang::En, &p.label), p.label, "profil sans traduction : {}", p.label);
        }
        for h in ff_core::HwAccel::ALL {
            let _ = tr(Lang::En, h.label());
        }
    }
